# 流程散文：唯一手写的部分。放这里而不是文档里，是为了与行为同提交更新
# ---------------------------------------------------------------------------

WORKFLOW = """\
## 新建一条引用

1. `uids` 查一个没被占用的 id（别自己编，撞了会变成 ambiguous）。
2. 两端各写一对范围标记：`<|e:<id>#<段>|> … <|/e:<id>#<段>|>`。
   单段可省段标签或写 `*`。标记**贴在外面**：要圈一段代码块，就把标记写在
   围栏外的上下两行，不要写进围栏里。
3. 每端在自己的范围**之内**写一份声明：`<|标签：对方id#段;h=…|(视图)>`。
   写入时 `h` 先留空，随后由 `rebind` 填。
4. 两端的标签必须取自**同一对互逆标签**（`引用对象`/`引用者`、
   `描述对象`/`描述者`、`规格`/`实现`、`被测物`/`测试`、`出处`/`依据`）。
   混用两对会被报 `role_conflict`。
5. 跑 `rebind --rel <id> --note <证据>` 核对并写下基线，再跑 `render` 刷视图。

## 改了内容之后

不用做任何事。`check` 会在另一端派生出一条漂移，工单里会说明是哪一端。

## 修一条漂移

1. `diag --changed <你改的文件>` 看闭包与工单。**若这条关系在环上**，
   §3.16 要求先把环上各端的表述**一起定稿**再逐条处理，否则逐条改会互相推翻。
2. 读两端内容，判断哪边才是对的，然后选一条路：
   - 内容改错了 → 改回去，漂移自己消失（记忆没动）。
   - 描述该更新 → 改描述方。
   - 现状就是对的 → `rebind --rel <id> --note <证据>`，把现状认作新基线。
3. `render` 刷视图。

## 两条禁令

- **渲染区不许手改**：它是纯输出，下次渲染会覆盖。
- **`h` 不许手改**：改它等于绕过证据做一次 `rebind`。要重新认基线，就跑
  `rebind`。

## 辨认本工具的产出

产出物（如抽查稿）文件头带 `<!-- refcheck:generated`，扫描时整份剔除。
示例路径按行标 `<!-- refcheck:example -->`，或整段用
`<!-- refcheck:example:start -->` … `:end` 包住。
"""


def _norm(text: str) -> str:
    """去掉标点与空白后再比。只做归一化，不做语义判断。"""
    drop = set(" \t　`，。、：；！？（）()「」『』·*|'\"")
    return "".join(ch for ch in text if ch not in drop)


def prose_leaks() -> list[str]:
    """表里的句子不许出现在代码里（**单向**门）。

    为什么是这个方向：正文的唯一来源是本表，代码只提供实例事实。于是「代码里
    出现了表里的句子」等价于「有人在代码里重述了通用判断」，而那正是两份正文
    各自演化的起点。

    这是**弱门**，得说清它弱在哪：它抓逐字抄（归一化后仍逐字），抓不到改写过的
    重述。留着它是因为实测里两处重复恰好都是逐字抄来的（`unverified` 的「跑
    `rebind` 核对并写下基线」、`orphan_segment` 的「有范围标记，但全库没有任何
    声明指向它」），而逐字抄是退化的第一步。抓不到的那部分只能靠审查，这不是
    缺陷：本工具对一切语义问题都是这个处境（确定性层判不了锚点对错，那里也是
    靠独立抽查）。
    """
    here = Path(__file__).resolve().parent
    mine = Path(__file__).name
    src: dict[str, str] = {}
    for p in sorted(here.glob("*.py")):
        if p.name != mine:
            src[p.name] = _norm(p.read_text(encoding="utf-8"))
    hits = []
    for st, (what, action, _) in STATE_DOC.items():
        for kind, sentence in (("意思", what), ("动作", action)):
            n = _norm(sentence)
            if len(n) < 8:              # 太短的短语（如「补闭标记」）不判
                continue
            for name, text in src.items():
                if n in text:
                    hits.append(f"`{st}` 的{kind}整句出现在 {name} 里：{sentence}")
    return hits


def selfcheck() -> list[str]:
    """表与代码的一致性自检。

    「把散落收成表」若不校验，只是把散落换了个地方。这里查三件：
    阻断状态是否都在状态表里，状态表里标阻断的是否真的在阻断集里（两个方向，
    单查一个方向时另一方向的错会静默），以及代码里有没有重述表里的句子。
    """
    from marks import BLOCKING
    problems = []
    for st in sorted(BLOCKING):
        if st not in STATE_DOC and st not in RESERVED_STATES:
            problems.append(f"状态 `{st}` 在 BLOCKING 里但不在 STATE_DOC 里")
    for st, (_, _, block) in STATE_DOC.items():
        if block and st not in BLOCKING:
            problems.append(f"状态 `{st}` 在 STATE_DOC 里标了阻断，"
                            f"但它不在 BLOCKING 里（显示与门控会不一致）")
    problems.extend(prose_leaks())
    return problems


def text() -> str:
    out = ["# refcheck 说明书", "",
           "本文件由工具生成，唯一权威。**不要手改**——改代码里的表，",
           "或改 `manual.py` 里的流程散文。", "", "## 命令", ""]
    for name, (rw, what, when) in COMMANDS.items():
        out.append(f"- `{name}`（{rw}）：{what}。何时用：{when}")
    out += ["", "## 字段", ""]
    for key, (what, who, editable) in FIELD_DOC.items():
        out.append(f"- `{key}`：{what}。谁写：{who}。能否手改：{editable}")
    out += ["", "## 状态 → 下一步动作", ""]
    for st, (what, action, block) in STATE_DOC.items():
        flag = "阻断" if block else "不阻断"
        out.append(f"- `{st}`（{flag}）：{what} → {action}")
    if RESERVED_STATES:
        out += ["", "设计里定义但当前未实现的状态："]
        for st, why in RESERVED_STATES.items():
            out.append(f"- `{st}`：{why}")
    out += ["", WORKFLOW]
    return "\n".join(out)


def brief() -> str:
    """精简版：注入用。只留必须知道的两条禁令与命令入口。"""
    out = ["# refcheck（精简）", "",
           "**两条禁令**：渲染区不许手改（下次渲染覆盖）；`h` 不许手改"
           "（等于绕过证据做一次 rebind）。", "",
           "**命令**（读写）："]
    for name, (rw, what, _) in COMMANDS.items():
        out.append(f"- `{name}`（{rw}）：{what}")
    out += ["", "完整说明书：`python tools/refcheck/refcheck.py manual`",
            "流程（建引用 / 改内容 / 修漂移）也在里面。"]
    return "\n".join(out)
